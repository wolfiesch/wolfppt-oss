def build_benchmark_adapters(
    namespace: Mapping[str, Any],
) -> tuple[BenchmarkAdapter, ...]:
    return tuple(
        BenchmarkAdapter(
            name=spec.name,
            operation=spec.operation,
            role=spec.role,
            available=cast(Callable[[], bool], namespace[spec.available]),
            run=cast(BenchmarkFn, namespace[spec.run]),
            unavailable_reason=(
                cast(Callable[[], str | None], namespace[spec.unavailable_reason])
                if spec.unavailable_reason is not None
                else None
            ),
        )
        for spec in BENCHMARK_ADAPTER_SPECS
    )


def default_benchmark_adapter_names(
    adapters: tuple[BenchmarkAdapter, ...],
) -> tuple[str, ...]:
    return tuple(
        adapter.name
        for adapter in adapters
        if not adapter.operation.startswith("dropin-")
    )
