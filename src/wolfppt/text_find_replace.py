"""Presentation-wide text find and replace with regex, case, and word options.

Matching runs over each paragraph's run text, so a match may span several
``a:r`` runs. A line break (``a:br``) or a field (``a:fld``) ends a matchable
stretch: field text is generated by PowerPoint and is never rewritten. The
replacement text lands in the run where the match starts and keeps that run's
formatting; the matched characters leave the later runs, whose properties and
remaining text stay as they were.

Edits are byte-surgical. Only the content of the ``a:t`` elements whose text
changes is rewritten, every other byte of an edited part is kept, and parts
without a match are copied as their original ZIP entries.
"""

from __future__ import annotations

import re
import tempfile
import zipfile
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, BinaryIO
from xml.parsers import expat

from .comment_edits import has_pending_comment_edits
from .package_parts import (
    InMemoryPackageSource,
    copy_open_package_with_replacements,
    open_package_source,
    rels_part_for_package_part,
    resolve_package_target,
)
from .presentation_save_state import has_pending_save_edits

A_NS = "http://schemas.openxmlformats.org/drawingml/2006/main"
P_NS = "http://schemas.openxmlformats.org/presentationml/2006/main"
R_NS = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
PKG_REL_NS = "http://schemas.openxmlformats.org/package/2006/relationships"

_A = A_NS + " "
_P = P_NS + " "
_SHAPE_TAGS = frozenset(
    _P + local for local in ("sp", "grpSp", "graphicFrame", "cxnSp", "pic", "contentPart")
)
_TEXT_BODY_TAGS = frozenset((_P + "txBody", _A + "txBody"))
_NOTES_SLIDE_REL = "/notesSlide"
_SLIDE_REL = "/slide"
_OFFICE_DOCUMENT_REL = "/officeDocument"
_XML_ILLEGAL = re.compile("[\x00-\x08\x0b\x0c\x0e-\x1f\ufffe\uffff]")


class TextFindReplaceError(ValueError):
    """Refusal raised for an invalid search request or an unreadable part."""


@dataclass(frozen=True)
class TextMatch:
    """One match location.

    ``start`` and ``end`` are character offsets into the paragraph text, where
    a line break counts as ``"\\n"`` and field text counts as shown. ``runs``
    lists the paragraph's ``a:r`` indexes the match touches.
    """

    part: str
    scope: str
    slide_index: int
    shape_id: int | None
    shape_name: str
    group_path: tuple[int, ...]
    table_cell: tuple[int, int] | None
    paragraph_index: int
    start: int
    end: int
    runs: tuple[int, ...]
    text: str
    replacement: str


@dataclass(frozen=True)
class TextReplaceResult:
    """Outcome of a replacement or dry run.

    ``changed_parts`` names the parts the replacement rewrites; for a dry run
    it names the parts it would rewrite, and nothing is written.
    """

    matches: tuple[TextMatch, ...]
    changed_parts: tuple[str, ...]
    dry_run: bool
    path: str | None = None

    @property
    def replacements(self) -> int:
        return len(self.matches)


@dataclass
class _Piece:
    run_index: int
    text: str
    content_start: int
    content_end: int


@dataclass
class _Paragraph:
    location: tuple[int | None, str, tuple[int, ...], tuple[int, int] | None, int]
    segments: list[tuple[int, list[_Piece]]] = field(default_factory=list)
    current: list[_Piece] = field(default_factory=list)
    segment_start: int = 0
    position: int = 0
    run_count: int = 0

    def close_segment(self) -> None:
        if self.current:
            self.segments.append((self.segment_start, self.current))
        self.current = []
        self.segment_start = self.position


def compile_search(
    search: str,
    *,
    regex: bool = False,
    ignore_case: bool = False,
    whole_word: bool = False,
) -> re.Pattern[str]:
    """Compile the search text under the requested options."""
    if not isinstance(search, str) or not search:
        raise TextFindReplaceError("search text must be a non-empty string")
    pattern = search if regex else re.escape(search)
    if whole_word:
        pattern = rf"(?<!\w)(?:{pattern})(?!\w)"
    try:
        return re.compile(pattern, re.IGNORECASE if ignore_case else 0)
    except re.error as exc:
        raise TextFindReplaceError(f"invalid regular expression: {exc}") from exc


def find_text(
    source: str | Path | InMemoryPackageSource,
    search: str,
    *,
    regex: bool = False,
    ignore_case: bool = False,
    whole_word: bool = False,
) -> tuple[TextMatch, ...]:
    """Return every match location in slides and notes, in presentation order."""
    return replace_text(
        source,
        None,
        search,
        "",
        regex=regex,
        ignore_case=ignore_case,
        whole_word=whole_word,
        dry_run=True,
    ).matches


def replace_text(
    source: str | Path | InMemoryPackageSource,
    output: str | Path | BinaryIO | None,
    search: str,
    replacement: str,
    *,
    regex: bool = False,
    ignore_case: bool = False,
    whole_word: bool = False,
    dry_run: bool = False,
) -> TextReplaceResult:
    """Replace text across slides and notes, or report matches with ``dry_run``.

    With ``regex=True`` the replacement may use group references such as
    ``\\1`` or ``\\g<name>``; otherwise it is inserted literally. Zero-length
    regex matches are skipped because they select no text.
    """
    if not isinstance(replacement, str):
        raise TextFindReplaceError("replacement must be a string")
    if dry_run and output is not None:
        raise TextFindReplaceError("dry_run writes nothing; omit output")
    if not dry_run and output is None:
        raise TextFindReplaceError("output is required unless dry_run is set")
    pattern = compile_search(search, regex=regex, ignore_case=ignore_case, whole_word=whole_word)
    expand = _expander(replacement, regex)
    package_source = source if isinstance(source, InMemoryPackageSource) else Path(source)
    with open_package_source(package_source) as package:
        names = set(package.namelist())
        matches: list[TextMatch] = []
        rewritten: dict[str, bytes] = {}
        for slide_index, scope, part in _text_parts(package, names):
            payload = package.read(part)
            part_matches, edited = _process_part(payload, part, scope, slide_index, pattern, expand)
            matches.extend(part_matches)
            if edited is not None and edited != payload:
                rewritten[part] = edited
        if not dry_run:
            target: Path | BinaryIO = (
                Path(output) if isinstance(output, (str, Path)) else output  # type: ignore[arg-type]
            )
            copy_open_package_with_replacements(package, target, rewritten)
    return TextReplaceResult(
        matches=tuple(matches),
        changed_parts=tuple(sorted(rewritten)),
        dry_run=dry_run,
        path=str(output) if isinstance(output, (str, Path)) else None,
    )


def presentation_find_text(
    presentation: Any, search: str, **options: bool
) -> tuple[TextMatch, ...]:
    """Read-only search, including text queued through live facade handles."""
    with presentation._mutation_lock:
        if presentation._disposed:
            raise RuntimeError("presentation is disposed")
        if _has_pending_presentation_edits(presentation):
            _require_live_source(presentation)
            from .text_find_replace_live import find_in_live_presentation

            return find_in_live_presentation(presentation, search, **options)
        return find_text(presentation._source_path, search, **options)


def presentation_replace_text(
    presentation: Any,
    search: str,
    replacement: str,
    *,
    dry_run: bool = False,
    reload: Callable[[Any], None],
    **options: bool,
) -> TextReplaceResult:
    """Keep queued edits and handles; clean sessions use byte-surgical edits."""
    with presentation._mutation_lock:
        if presentation._disposed:
            raise RuntimeError("presentation is disposed")
        if _has_pending_presentation_edits(presentation):
            _require_live_source(presentation)
            from .text_find_replace_live import replace_in_live_presentation

            return replace_in_live_presentation(
                presentation, search, replacement, dry_run=dry_run, **options
            )
        source = presentation._source_path
        if dry_run:
            return replace_text(source, None, search, replacement, dry_run=True, **options)
        staged_dir: tempfile.TemporaryDirectory[str] | None = tempfile.TemporaryDirectory(
            prefix="wolfppt-find-replace-"
        )
        try:
            staged_path = Path(staged_dir.name) / "presentation.pptx"
            result = replace_text(source, staged_path, search, replacement, **options)
            _check_clean_replace_locks(presentation, result)
            staged: Any = staged_path
            if not result.changed_parts:
                staged_dir.cleanup()
                return TextReplaceResult(result.matches, (), False)
            if isinstance(source, InMemoryPackageSource):
                staged = InMemoryPackageSource(staged_path.read_bytes())
                staged_dir.cleanup()
                staged_dir = None
        except BaseException:
            if staged_dir is not None:
                staged_dir.cleanup()
            raise
        previous_tempdir = presentation._source_tempdir
        presentation._source_path = staged
        if staged_dir is not None:
            presentation._source_tempdir = staged_dir
            if previous_tempdir is not None:
                previous_tempdir.cleanup()
        reload(staged)
        return TextReplaceResult(result.matches, result.changed_parts, False)


def _check_clean_replace_locks(presentation: Any, result: TextReplaceResult) -> None:
    """Refuse a staged replacement that edits a shape whose no_text_edit lock is set.

    Runs before the staged package replaces the source, so a refusal leaves the
    presentation and its handles untouched.
    """
    if not presentation.enforce_shape_locks:
        return
    from .shape_locks import check_text_edit_lock

    checked: set[tuple[int, int]] = set()
    for match in result.matches:
        # Table cells live in graphic frames, which carry no no_text_edit flag.
        if match.scope != "slide" or match.table_cell is not None or match.shape_id is None:
            continue
        if match.text == match.replacement or (match.slide_index, match.shape_id) in checked:
            continue
        checked.add((match.slide_index, match.shape_id))
        shape = _shape_by_id(presentation.slides[match.slide_index].shapes, match.shape_id)
        if shape is not None:
            check_text_edit_lock(shape)


def _shape_by_id(shapes: Any, shape_id: int) -> Any:
    for shape in shapes:
        if shape.shape_id == shape_id:
            return shape
        if shape._payload.get("kind") == "group":
            found = _shape_by_id(shape.shapes, shape_id)
            if found is not None:
                return found
    return None


def _has_pending_presentation_edits(presentation: Any) -> bool:
    slide_show = presentation._slide_show
    return bool(
        has_pending_save_edits(presentation)
        or has_pending_comment_edits(presentation)
        or presentation._pending_vba_modules
        or presentation._pending_vba_removal
        or presentation._pending_web_extensions
        or (slide_show is not None and slide_show.dirty)
    )


def _require_live_source(presentation: Any) -> None:
    if isinstance(presentation._source_path, InMemoryPackageSource):
        raise TextFindReplaceError(
            "save pending presentation edits before finding or replacing text "
            "in a no_disk presentation"
        )
    fields = presentation._lifecycle_fields
    if fields is not None and fields.dirty:
        raise TextFindReplaceError("save pending field edits before finding or replacing text")
    if _has_notes_tables(presentation._source_path):
        raise TextFindReplaceError(
            "save pending edits before finding or replacing text "
            "in a presentation with notes tables"
        )


def _has_notes_tables(source: Any) -> bool:
    # Notes facade payloads omit table inventories, and their table writers
    # would share slide-indexed queues. Inspect source bytes before planning.
    with open_package_source(source) as package:
        for _, scope, part in _text_parts(package, set(package.namelist())):
            if scope != "notes":
                continue
            found = False
            parser = expat.ParserCreate(namespace_separator=" ")

            def start(name: str, _attrs: dict[str, str]) -> None:
                nonlocal found
                if name == _A + "tbl":
                    found = True

            parser.StartElementHandler = start
            _parse(parser, package.read(part), part)
            if found:
                return True
    return False


def _expander(replacement: str, regex: bool) -> Callable[[re.Match[str]], str]:
    if regex:

        def expand(match: re.Match[str]) -> str:
            try:
                return match.expand(replacement)
            except (re.error, IndexError) as exc:
                raise TextFindReplaceError(f"invalid replacement template: {exc}") from exc
    else:

        def expand(match: re.Match[str]) -> str:
            return replacement

    return expand


def _text_parts(package: zipfile.ZipFile, names: set[str]) -> list[tuple[int, str, str]]:
    """``(slide_index, scope, part)`` for each slide then its notes slide."""
    presentation_part = _related_parts(package, names, "", _OFFICE_DOCUMENT_REL)
    if not presentation_part:
        raise TextFindReplaceError("the package has no presentation part")
    main = presentation_part[0]
    slide_targets = dict(_relationship_targets(package, names, main, _SLIDE_REL))
    parts: list[tuple[int, str, str]] = []
    for slide_index, rel_id in enumerate(_slide_relationship_ids(package.read(main))):
        slide = slide_targets.get(rel_id)
        if slide is None or slide not in names:
            continue
        parts.append((slide_index, "slide", slide))
        for notes in _related_parts(package, names, slide, _NOTES_SLIDE_REL):
            parts.append((slide_index, "notes", notes))
    return parts


def _slide_relationship_ids(payload: bytes) -> list[str]:
    ids: list[str] = []
    parser = expat.ParserCreate(namespace_separator=" ")

    def start(name: str, attrs: dict[str, str]) -> None:
        if name == _P + "sldId":
            rel_id = attrs.get(R_NS + " id")
            if rel_id:
                ids.append(rel_id)

    parser.StartElementHandler = start
    _parse(parser, payload, "presentation part")
    return ids


def _relationship_targets(
    package: zipfile.ZipFile, names: set[str], owner: str, suffix: str
) -> list[tuple[str, str]]:
    rels = rels_part_for_package_part(owner) if owner else "_rels/.rels"
    if rels not in names:
        return []
    found: list[tuple[str, str]] = []
    parser = expat.ParserCreate(namespace_separator=" ")

    def start(name: str, attrs: dict[str, str]) -> None:
        if name != PKG_REL_NS + " Relationship":
            return
        if attrs.get("TargetMode") == "External":
            return
        if attrs.get("Type", "").endswith(suffix) and attrs.get("Target"):
            found.append((attrs.get("Id", ""), resolve_package_target(owner, attrs["Target"])))

    parser.StartElementHandler = start
    _parse(parser, package.read(rels), rels)
    return found


def _related_parts(package: zipfile.ZipFile, names: set[str], owner: str, suffix: str) -> list[str]:
    return [
        target
        for _, target in _relationship_targets(package, names, owner, suffix)
        if target in names
    ]


def _parse(parser: Any, payload: bytes, label: str) -> None:
    if payload[:2] in (b"\xff\xfe", b"\xfe\xff"):
        raise TextFindReplaceError(f"{label} is not UTF-8 encoded")
    try:
        parser.Parse(payload, True)
    except expat.ExpatError as exc:
        raise TextFindReplaceError(f"{label} is not well-formed XML: {exc}") from exc


def _start_tag_end(payload: bytes, index: int) -> int:
    """Offset just past the ``>`` that closes the start tag at ``index``."""
    quote = 0
    for offset in range(index, len(payload)):
        byte = payload[offset]
        if quote:
            if byte == quote:
                quote = 0
        elif byte in (0x22, 0x27):
            quote = byte
        elif byte == 0x3E:
            return offset + 1
    raise TextFindReplaceError("unterminated start tag")


def _process_part(
    payload: bytes,
    part: str,
    scope: str,
    slide_index: int,
    pattern: re.Pattern[str],
    expand: Callable[[re.Match[str]], str],
) -> tuple[list[TextMatch], bytes | None]:
    from xml.sax.saxutils import escape

    parser = expat.ParserCreate(namespace_separator=" ")
    parser.buffer_text = True
    stack: list[str] = []
    shapes: list[list[Any]] = []
    tables: list[list[int]] = []
    bodies: list[list[int]] = []
    paragraphs: list[_Paragraph] = []
    text_target: list[Any] = []
    matches: list[TextMatch] = []
    splices: list[tuple[int, int, str]] = []

    def location() -> tuple[int | None, str, tuple[int, ...], tuple[int, int] | None, int]:
        shape = shapes[-1] if shapes else [None, None, ""]
        groups = tuple(
            entry[1] for entry in shapes[:-1] if entry[0] == _P + "grpSp" and entry[1] is not None
        )
        cell = (tables[-1][0], tables[-1][1]) if tables else None
        index = bodies[-1][0] if bodies else 0
        if bodies:
            bodies[-1][0] += 1
        return (shape[1], shape[2], groups, cell, index)

    def start(name: str, attrs: dict[str, str]) -> None:
        parent = stack[-1] if stack else ""
        stack.append(name)
        if name in _SHAPE_TAGS:
            shapes.append([name, None, ""])
        elif name == _P + "cNvPr" and shapes and shapes[-1][1] is None:
            raw_id = attrs.get("id", "")
            shapes[-1][1] = int(raw_id) if raw_id.isdigit() else None
            shapes[-1][2] = attrs.get("name", "")
        elif name in _TEXT_BODY_TAGS:
            bodies.append([0])
        elif name == _A + "tbl":
            tables.append([-1, -1])
        elif name == _A + "tr" and tables:
            tables[-1][0] += 1
            tables[-1][1] = -1
        elif name == _A + "tc" and tables:
            tables[-1][1] += 1
        elif name == _A + "p":
            paragraphs.append(_Paragraph(location()))
        elif not paragraphs:
            return
        elif name == _A + "r" and parent == _A + "p":
            paragraphs[-1].run_count += 1
        elif name in (_A + "br", _A + "fld") and parent == _A + "p":
            paragraphs[-1].close_segment()
            if name == _A + "br":
                paragraphs[-1].position += 1
                paragraphs[-1].segment_start += 1
        elif name == _A + "t" and parent == _A + "r" and stack[-3] == _A + "p":
            tag_end = _start_tag_end(payload, parser.CurrentByteIndex)
            text_target.append(_Piece(paragraphs[-1].run_count - 1, "", tag_end, tag_end))
        elif name == _A + "t":
            # Field text and other unmatched text still advance paragraph offsets.
            text_target.append([])

    def end(name: str) -> None:
        stack.pop()
        if name in _SHAPE_TAGS and shapes:
            shapes.pop()
        elif name in _TEXT_BODY_TAGS and bodies:
            bodies.pop()
        elif name == _A + "tbl" and tables:
            tables.pop()
        elif name == _A + "p" and paragraphs:
            paragraph = paragraphs.pop()
            paragraph.close_segment()
            _match_paragraph(paragraph, part, scope, slide_index, pattern, expand, matches, splices)
        elif name == _A + "fld" and paragraphs:
            paragraphs[-1].segment_start = paragraphs[-1].position
        elif name == _A + "t" and text_target:
            target = text_target.pop()
            if isinstance(target, _Piece):
                # An empty ``<a:t/>`` keeps ``content_end`` at its tag end; empty
                # pieces never receive replacement text, so they are never spliced.
                target.content_end = max(parser.CurrentByteIndex, target.content_start)
                paragraphs[-1].current.append(target)
                paragraphs[-1].position += len(target.text)
            else:
                paragraphs[-1].position += len("".join(target))

    def characters(data: str) -> None:
        if not text_target:
            return
        target = text_target[-1]
        if isinstance(target, _Piece):
            target.text += data
        elif isinstance(target, list):
            target.append(data)

    parser.StartElementHandler = start
    parser.EndElementHandler = end
    parser.CharacterDataHandler = characters
    _parse(parser, payload, part)
    if not splices:
        return matches, None
    edited = bytearray(payload)
    for content_start, content_end, text in sorted(splices, reverse=True):
        edited[content_start:content_end] = escape(text).encode("utf-8")
    return matches, bytes(edited)


def _match_paragraph(
    paragraph: _Paragraph,
    part: str,
    scope: str,
    slide_index: int,
    pattern: re.Pattern[str],
    expand: Callable[[re.Match[str]], str],
    matches: list[TextMatch],
    splices: list[tuple[int, int, str]],
) -> None:
    shape_id, shape_name, groups, cell, paragraph_index = paragraph.location
    for base, pieces in paragraph.segments:
        text = "".join(piece.text for piece in pieces)
        bounds: list[int] = []
        offset = 0
        for piece in pieces:
            bounds.append(offset)
            offset += len(piece.text)
        found: list[tuple[int, int, str, tuple[int, ...]]] = []
        for match in pattern.finditer(text):
            begin, finish = match.span()
            if begin == finish:
                continue
            new_text = expand(match)
            if _XML_ILLEGAL.search(new_text):
                raise TextFindReplaceError("replacement contains characters XML cannot carry")
            touched = tuple(
                index
                for index, piece in enumerate(pieces)
                if bounds[index] < finish and bounds[index] + len(piece.text) > begin
            )
            found.append((begin, finish, new_text, touched))
            matches.append(
                TextMatch(
                    part=part,
                    scope=scope,
                    slide_index=slide_index,
                    shape_id=shape_id,
                    shape_name=shape_name,
                    group_path=groups,
                    table_cell=cell,
                    paragraph_index=paragraph_index,
                    start=base + begin,
                    end=base + finish,
                    runs=tuple(pieces[index].run_index for index in touched),
                    text=match.group(0),
                    replacement=new_text,
                )
            )
        if not found:
            continue
        texts = [piece.text for piece in pieces]
        for begin, finish, new_text, touched in reversed(found):
            for position, index in enumerate(touched):
                local_start = max(begin - bounds[index], 0)
                local_end = min(finish - bounds[index], len(pieces[index].text))
                inserted = new_text if position == 0 else ""
                texts[index] = texts[index][:local_start] + inserted + texts[index][local_end:]
        for piece, new_text in zip(pieces, texts, strict=False):
            if new_text != piece.text:
                splices.append((piece.content_start, piece.content_end, new_text))
